import { Schema as S } from "effect"
import { defineMessageUnion } from "foldkit/message"
import { UrlRequest } from "foldkit/navigation"
import { Url } from "foldkit/url"
import { CommandLogEntry } from "@akter/cloud-api"
import { CommandAnswer } from "../commands/model.ts"
import { DevicePage } from "../device/model.ts"
import { Workspace } from "../workspace/model.ts"
import { Dialog } from "./model.ts"
import { PageData } from "./page.ts"
import { Preference } from "./theme.ts"

/** Everything that can happen in the console, named for what happened. */
export const Message = defineMessageUnion({
  ChangedUrl: { url: Url },
  RequestedUrl: { request: UrlRequest },
  RequestedHref: { href: S.String },
  LoadedPage: { page: S.Option(PageData), sample: S.Boolean },
  FailedPage: { kind: S.String, message: S.String },
  RetriedPage: {},
  LoadedWorkspace: { workspace: Workspace },
  ToggledDrawer: {},
  ClosedDrawer: {},
  OpenedPalette: {},
  ToggledPalette: {},
  ClosedPalette: {},
  ChangedPaletteQuery: { query: S.String },
  MovedPaletteSelection: { step: S.Literals([1, -1]) },
  HighlightedPaletteItem: { id: S.String },
  ChosePaletteItem: {},
  SettledPaletteQuery: { query: S.String },
  FoundActors: { query: S.String, actorTypes: S.Array(S.String), actors: S.Array(S.String) },
  ChoseTheme: { preference: Preference },
  ChangedField: { name: S.String, value: S.String },
  ToggledSetting: { key: S.String },
  ChoseSetting: { key: S.String, value: S.String },
  ChangedSettingsQuery: { query: S.String },
  SubmittedForm: { form: S.String },
  OpenedDialog: { dialog: Dialog },
  ClosedDialog: {},
  ConfirmedDialog: {},
  CopiedText: { text: S.String, label: S.String },
  DismissedToast: { id: S.String },
  ToggledTail: {},
  ChangedTailFilter: { filter: S.String },
  RetriedDeadLetter: { id: S.String },
  RetriedAllDeadLetters: {},
  SignedOut: {},
  CompletedAuth: {
    href: S.String,
    refresh: S.Boolean,
    title: S.optional(S.String),
    description: S.optional(S.String),
  },
  FailedAction: { message: S.String },
  Mutated: { title: S.String, description: S.optional(S.String), reload: S.Boolean },
  FailedMutation: { message: S.String },
  ChangedDeployment: { href: S.String, title: S.String, description: S.String },
  FailedDeploymentChange: { message: S.String },
  CreatedKey: { name: S.String, secret: S.String },
  SentRecoveryEmail: {},
  ResentVerification: {},
  AnsweredDevice: { code: S.String, page: DevicePage },
  ConnectedTail: { session: S.Finite },
  StreamedTurn: { session: S.Finite, entry: CommandLogEntry },
  StoppedTail: { session: S.Finite, kind: S.String, message: S.String },
  AnsweredCommand: { session: S.Finite, answer: CommandAnswer },
  FailedCommand: { session: S.Finite, kind: S.String, message: S.String },
  PreparedCommandId: { session: S.Finite, id: S.String },
  CompletedEffect: {},
})
export type Message = typeof Message.Type

export const {
  ChangedUrl,
  RequestedUrl,
  RequestedHref,
  LoadedPage,
  FailedPage,
  RetriedPage,
  LoadedWorkspace,
  ToggledDrawer,
  ClosedDrawer,
  OpenedPalette,
  ToggledPalette,
  ClosedPalette,
  ChangedPaletteQuery,
  MovedPaletteSelection,
  HighlightedPaletteItem,
  ChosePaletteItem,
  SettledPaletteQuery,
  FoundActors,
  ChoseTheme,
  ChangedField,
  ToggledSetting,
  ChoseSetting,
  ChangedSettingsQuery,
  SubmittedForm,
  OpenedDialog,
  ClosedDialog,
  ConfirmedDialog,
  CopiedText,
  DismissedToast,
  ToggledTail,
  ChangedTailFilter,
  RetriedDeadLetter,
  RetriedAllDeadLetters,
  SignedOut,
  CompletedAuth,
  FailedAction,
  Mutated,
  FailedMutation,
  ChangedDeployment,
  FailedDeploymentChange,
  CreatedKey,
  SentRecoveryEmail,
  ResentVerification,
  AnsweredDevice,
  ConnectedTail,
  StreamedTurn,
  StoppedTail,
  AnsweredCommand,
  FailedCommand,
  PreparedCommandId,
  CompletedEffect,
} = Message
